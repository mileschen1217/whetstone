import pytest

from inventory import api


def setup_function():
    api._stock.clear()
    api._holds.clear()


def test_reserve_more_than_stock():
    api.add("bolt", 1)
    with pytest.raises(LookupError):
        api.reserve("bolt", 2, 0)


def test_hold_expires_after_600_seconds():
    api.add("bolt", 5)
    api.reserve("bolt", 2, 0)
    api.expire(601)
    assert api.held("bolt") == 0


def test_release_forgets_the_hold():
    api.add("bolt", 5)
    h = api.reserve("bolt", 2, 0)
    api.release(h)
    assert api.held("bolt") == 0
