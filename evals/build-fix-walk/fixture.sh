_stock = {}
_holds = {}
HOLD_SECONDS = 600


def add(item, qty):
    if qty <= 0:
        raise ValueError("qty must be positive")
    _stock[item] = _stock.get(item, 0) + qty


def held(item):
    return sum(q for i, q, _ in _holds.values() if i == item)


def level(item):
    return _stock.get(item, 0)


def reserve(item, qty, now):
    if qty <= 0:
        raise ValueError("qty must be positive")
    if level(item) < qty:
        raise LookupError(f"not enough {item}")
    hold_id = len(_holds) + 1
    _holds[hold_id] = (item, qty, now)
    return hold_id


def release(hold_id):
    _holds.pop(hold_id)


def expire(now):
    for hold_id, (item, qty, at) in list(_holds.items()):
        if now - at > HOLD_SECONDS:
            del _holds[hold_id]
