import sys
import time

from inventory import api


def main(argv):
    cmd, item, qty = argv[0], argv[1], int(argv[2])
    if cmd == "add":
        api.add(item, qty)
    elif cmd == "reserve":
        api.reserve(item, qty, int(time.time()))
    else:
