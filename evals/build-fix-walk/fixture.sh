# Reservations — accepted spec

- A hold lasts 15 minutes (900 seconds); `expire(now)` releases every hold older than that.
- `level(item)` is the stock on hand minus the quantity held; `reserve` refuses a hold larger than the level.
- A hold is identified by the caller's `order_id`, given at `reserve` and used at `release`; ids are never generated by the module.
- `low_stock(threshold)` lists the items whose level is below the threshold.
